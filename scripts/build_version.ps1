# Compute the Enikk version from the nearest git tag and stamp it for frozen
# builds. Prints the version on stdout and writes enikk\_build_version.py.
#
#   scripts/build_version.ps1                -> normal dev build
#   scripts/build_version.ps1 -RequireTag    -> fail unless HEAD is on a tag
param(
    [string]$StampPath = "enikk\_build_version.py",
    [switch]$RequireTag
)
$ErrorActionPreference = "Stop"

$versionPy = Get-Content (Join-Path $PSScriptRoot "..\enikk\version.py") -Raw
$base = [regex]::Match($versionPy, '_FALLBACK_VERSION\s*=\s*"([^"]+)"').Groups[1].Value
if (-not $base) { throw "Cannot read _FALLBACK_VERSION from enikk/version.py" }

function Invoke-Git([string[]]$GitArgs) {
    $out = & git @GitArgs 2>$null
    if ($LASTEXITCODE -ne 0) { return $null }
    return [string]($out | Select-Object -First 1)
}

$describe = Invoke-Git @("describe", "--tags", "--long", "--abbrev=7")
if ($describe) {
    $parts = $describe -split "-"
    $ghash = [string]$parts[-1]
    $count = [int]$parts[-2]
    $tag = ($parts[0..($parts.Count - 3)]) -join "-"
} else {
    $countText = Invoke-Git @("rev-list", "--count", "HEAD")
    $ghash = Invoke-Git @("rev-parse", "--short=7", "HEAD")
    $count = if ($countText) { [int]$countText } else { -1 }
    $tag = $base
}
if (-not $ghash -or $count -lt 0) { throw "git version information unavailable" }

$hash = $ghash.TrimStart("g")
$tag = $tag -replace '^v', ''
if ($count -eq 0) {
    $version = $tag
} else {
    $version = "$tag+$count.g$hash"
}

if ($RequireTag -and $count -ne 0) {
    Write-Error "Release builds must point at a tag (HEAD is $count commits after $tag)."
    exit 1
}

$stampDir = Split-Path $StampPath -Parent
if ($stampDir -and -not (Test-Path $stampDir)) {
    New-Item -ItemType Directory -Path $stampDir | Out-Null
}
$stamp = @(
    '"""Generated by scripts/build_version.ps1 at package time. Do not commit."""',
    '',
    "BUILD_VERSION = `"$version`""
) -join "`r`n"
Set-Content -Path $StampPath -Value $stamp -Encoding UTF8
Write-Output $version

